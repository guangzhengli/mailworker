import {
  agentIdentityDto,
  apiKeyDto,
  capabilitiesDto,
  createEnvironmentBody,
  createIdentityBody,
  createInboxBody,
  createKeyBody,
  createNoteBody,
  createWebhookBody,
  deliveryDto,
  deliveryTimelineDto,
  diagnosticsDto,
  environmentDto,
  errorResponse,
  inboxDto,
  labelDto,
  labelUsageDto,
  messageDto,
  messageSummaryDto,
  noteDto,
  rejectDeliveryBody,
  renameLabelBody,
  sendBatchBody,
  sendBatchResponse,
  sendBody,
  sendResponse,
  suppressionDto,
  updateInboxBody,
  updateMessageBody,
  updateMessagesBody,
  waitQuery,
  waitResponse,
  webhookDto,
} from "@mailworker/contract";
import { z } from "zod";

export const schemas = {
  agentIdentity: agentIdentityDto,
  apiKey: apiKeyDto,
  capabilities: capabilitiesDto,
  createEnvironment: createEnvironmentBody,
  createIdentity: createIdentityBody,
  createInbox: createInboxBody,
  createKey: createKeyBody,
  createWebhook: createWebhookBody,
  delivery: deliveryDto,
  deliveryTimeline: deliveryTimelineDto,
  diagnostics: diagnosticsDto,
  environment: environmentDto,
  error: errorResponse,
  inbox: inboxDto,
  updateInbox: updateInboxBody,
  updateMessage: updateMessageBody,
  updateMessages: updateMessagesBody,
  updatedMessages: z.object({ updated: z.number().int().positive() }),
  label: labelDto,
  labels: z.object({ items: z.array(labelUsageDto) }),
  renameLabel: renameLabelBody,
  createNote: createNoteBody,
  note: noteDto,
  notes: z.object({ items: z.array(noteDto) }),
  message: messageDto,
  messageSummary: messageSummaryDto,
  rejectDelivery: rejectDeliveryBody,
  send: sendBody,
  sendBatch: sendBatchBody,
  sendBatchResponse,
  sendResponse,
  suppression: suppressionDto,
  waitQuery,
  waitResponse,
  webhook: webhookDto,

  inboxPage: z.object({ items: z.array(inboxDto), cursor: z.string().nullable() }),
  messagePage: z.object({ items: z.array(messageSummaryDto), cursor: z.string().nullable() }),
  deliveryPage: z.object({ items: z.array(deliveryDto), cursor: z.string().nullable() }),
  thread: z.object({ items: z.array(messageDto) }),
  environments: z.object({ items: z.array(environmentDto) }),
  identities: z.object({ items: z.array(agentIdentityDto) }),
  apiKeys: z.object({ items: z.array(apiKeyDto) }),
  mintedApiKey: apiKeyDto.extend({ token: z.string() }),
  webhooks: z.object({ items: z.array(webhookDto) }),
  createdWebhook: webhookDto.extend({ secret: z.string() }),
  suppressions: z.object({ items: z.array(suppressionDto) }),
  injectedMessage: z.discriminatedUnion("outcome", [
    z.object({ outcome: z.literal("stored"), message: messageDto }),
    z.object({ outcome: z.literal("duplicate"), messageId: z.string() }),
  ]),
} as const;

export type RuntimeSchema<Output = unknown> = {
  readonly safeParse: (input: unknown) => z.ZodSafeParseResult<Output>;
};
